#!/usr/bin/env node
/**
 * Uploads the demo product imagery in public/products/ into the
 * `product-images` Supabase Storage bucket, then writes a ready-to-run
 * copy of the seed with your project's real storage URLs filled in.
 *
 *   npm run seed:images
 *
 * Needs NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in
 * .env.local. The service-role key is required because the bucket's
 * write policy is admin-only.
 */

import { createClient } from "@supabase/supabase-js";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { join, extname, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIR = join(ROOT, "public", "products");
const SEED_IN = join(ROOT, "supabase", "seed.sql");
const SEED_OUT = join(ROOT, "supabase", "seed.generated.sql");

const BUCKET = "product-images";
const PLACEHOLDER =
  "https://YOUR-PROJECT-REF.supabase.co/storage/v1/object/public/product-images";

const CONTENT_TYPES = {
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".webp": "image/webp",
  ".avif": "image/avif",
};

function fail(message) {
  console.error(`\n  ✗ ${message}\n`);
  process.exit(1);
}

/** Minimal .env parser — avoids pulling in a dependency just for this. */
async function loadEnv() {
  for (const file of [".env.local", ".env"]) {
    let raw;
    try {
      raw = await readFile(join(ROOT, file), "utf8");
    } catch {
      continue;
    }
    for (const line of raw.split("\n")) {
      const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
      if (!match) continue;
      const [, key, value] = match;
      if (!process.env[key]) {
        process.env[key] = value.trim().replace(/^["']|["']$/g, "");
      }
    }
  }
}

await loadEnv();

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!url) fail("NEXT_PUBLIC_SUPABASE_URL is not set in .env.local");
if (!serviceKey) {
  fail(
    "SUPABASE_SERVICE_ROLE_KEY is not set in .env.local.\n" +
      "    Find it under Project Settings → API → service_role. Server only — never commit it.",
  );
}

const supabase = createClient(url, serviceKey, {
  auth: { persistSession: false, autoRefreshToken: false },
});

// ── 1. Make sure the bucket exists ────────────────────────────
const { data: buckets, error: listError } = await supabase.storage.listBuckets();
if (listError) fail(`Could not reach Storage: ${listError.message}`);

if (!buckets.some((b) => b.name === BUCKET)) {
  console.log(`  • Bucket "${BUCKET}" not found — creating it.`);
  const { error } = await supabase.storage.createBucket(BUCKET, {
    public: true,
    fileSizeLimit: 5 * 1024 * 1024,
    allowedMimeTypes: Object.values(CONTENT_TYPES),
  });
  if (error) fail(`Could not create the bucket: ${error.message}`);
  console.log(
    "    Run supabase/migrations/0002_storage.sql too, so admins can upload from the app.",
  );
} else {
  console.log(`  • Bucket "${BUCKET}" found.`);
}

// ── 2. Upload every image ─────────────────────────────────────
const files = (await readdir(SOURCE_DIR))
  .filter((f) => extname(f).toLowerCase() in CONTENT_TYPES)
  .sort();

if (files.length === 0) fail(`No images found in ${SOURCE_DIR}`);

console.log(`  • Uploading ${files.length} images…\n`);

let uploaded = 0;
for (const name of files) {
  const body = await readFile(join(SOURCE_DIR, name));
  const { error } = await supabase.storage.from(BUCKET).upload(name, body, {
    contentType: CONTENT_TYPES[extname(name).toLowerCase()],
    upsert: true, // re-running the script replaces rather than erroring
    cacheControl: "31536000",
  });

  if (error) {
    console.log(`    ✗ ${name.padEnd(30)} ${error.message}`);
  } else {
    uploaded += 1;
    console.log(`    ✓ ${name.padEnd(30)} ${(body.length / 1024) | 0} KB`);
  }
}

// ── 3. Confirm the public URLs actually serve ─────────────────
const base = `${url.replace(/\/$/, "")}/storage/v1/object/public/${BUCKET}`;
const probe = files[0];
const probeResponse = await fetch(`${base}/${probe}`, { method: "HEAD" });

console.log(
  `\n  • Public URL check: ${probeResponse.status} ${base}/${probe}`,
);
if (!probeResponse.ok) {
  console.log(
    "    The bucket may not be public. Check Storage → product-images → Settings.",
  );
}

// ── 4. Write a seed with the real URLs baked in ───────────────
const seed = await readFile(SEED_IN, "utf8");
if (!seed.includes(PLACEHOLDER)) {
  console.log("\n  ! seed.sql no longer contains the placeholder URL — skipping generation.");
} else {
  const generated =
    `-- GENERATED by scripts/upload-product-images.mjs — do not edit.\n` +
    `-- Storage URLs resolved for ${url}\n` +
    `-- Edit supabase/seed.sql instead, then re-run: npm run seed:images\n\n` +
    seed.split(PLACEHOLDER).join(base);
  await writeFile(SEED_OUT, generated, "utf8");
  console.log(`  • Wrote supabase/seed.generated.sql`);
}

console.log(
  `\n  Done — ${uploaded}/${files.length} uploaded.\n` +
    `  Next: run supabase/seed.generated.sql in the Supabase SQL editor.\n`,
);
